function flipV(s) {
  const c = makeCanvas(s.w, s.h), x = c.getContext('2d');
  x.translate(0, s.h); x.scale(1, -1); x.drawImage(s.c, 0, 0);
  return mkSprite(c);
}
function swapRows(rows, a, b) {
  return rows.map((r) => r.replace(/./g, (ch) => (ch === a ? b : ch === b ? a : ch)));
}

